#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { relayDiagram, relayTable } from "xpi-relay";

const docPath = resolve(fileURLToPath(new URL("..", import.meta.url)), "docs/relay.md");

const blocks = [
	{ name: "relay-diagram", render: () => `\`\`\`mermaid\n${relayDiagram()}\n\`\`\`` },
	{ name: "relay-table", render: relayTable },
] as const;

/** `current` with the content between each pair of marker comments replaced by the generated text. */
export function renderRelayDocs(current: string): string {
	let text = current;
	for (const { name, render } of blocks) {
		const start = `<!-- ${name}:start (generated by npm run generate:relay-docs; do not edit) -->`;
		const end = `<!-- ${name}:end -->`;
		const from = text.indexOf(`<!-- ${name}:start`);
		const to = from < 0 ? -1 : text.indexOf(end, from);
		if (from < 0 || to < from) throw new Error(`docs/relay.md has no ${name} markers`);
		text = `${text.slice(0, from)}${start}\n${render()}\n${text.slice(to)}`;
	}
	return text;
}

function generate(): void {
	const current = readFileSync(docPath, "utf-8");
	const next = renderRelayDocs(current);
	if (next !== current) writeFileSync(docPath, next, "utf-8");
	console.log("Generated packages/xpi-coding-agent/docs/relay.md");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	generate();
}
